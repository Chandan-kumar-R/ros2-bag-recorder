"""
Install (or remove) the Ubuntu application launcher.

The dashboard needs a sourced ROS workspace to run, and a .desktop file
launched from the GNOME grid inherits none of that. So the generated entry
sources /opt/ros/<distro>/setup.bash and the workspace this package was
installed into before exec'ing the app - the same two lines the operator would
otherwise type.

Run:
    ros2 run rosbag_recorder_ui install_desktop_entry
    ros2 run rosbag_recorder_ui install_desktop_entry --uninstall
"""
import argparse
import os
import shutil
import stat
import subprocess
import sys

from ament_index_python.packages import get_package_prefix

from rosbag_recorder_ui.core import icons

APP_ID = 'rosbag-recorder-ui'
DESKTOP_NAME = f'{APP_ID}.desktop'

LAUNCHER_TEMPLATE = """#!/usr/bin/env bash
# Generated by "ros2 run rosbag_recorder_ui install_desktop_entry".
# Re-run that command if the workspace moves.
set -e

if [ -f "{ros_setup}" ]; then
  # shellcheck disable=SC1090
  source "{ros_setup}"
fi
if [ -f "{workspace_setup}" ]; then
  # shellcheck disable=SC1090
  source "{workspace_setup}"
fi
{domain_line}

# Start the whole stack, not just the window: a dashboard with no bridge can
# see the ROS graph but cannot record anything.
USE_BRIDGE=true

if [ "${{1:-}}" = "--ui-only" ]; then
  # Explicit "the bridge lives on the robot" mode.
  USE_BRIDGE=false
  shift
elif timeout 8 ros2 node list 2>/dev/null | grep -q 'rosbag_recorder_bridge'; then
  # A bridge is already on this ROS_DOMAIN_ID. Starting a second one would put
  # two nodes on the same service names, so attach to the existing one instead.
  echo "A recorder bridge is already running; connecting to it."
  USE_BRIDGE=false
fi

exec ros2 launch rosbag_recorder_ui dashboard.launch.py \\
    use_bridge:="$USE_BRIDGE" "$@"
"""

DESKTOP_TEMPLATE = """[Desktop Entry]
Type=Application
Version=1.0
Name=ROS 2 Bag Recorder
GenericName=Rosbag Recording Dashboard
Comment=Configure, start, monitor and stop ROS 2 bag recordings
Exec={launcher}
Icon={icon}
Terminal=false
Categories=Development;
Keywords=ROS;ROS2;rosbag;rosbag2;recording;robotics;mcap;
StartupNotify=true
StartupWMClass=rosbag_recorder_ui
Actions=UiOnly;

[Desktop Action UiOnly]
Name=Dashboard only (bridge runs elsewhere)
Exec={launcher} --ui-only
"""


def _data_home():
    return os.environ.get('XDG_DATA_HOME') or os.path.expanduser('~/.local/share')


def paths():
    data_home = _data_home()
    return {
        'desktop': os.path.join(data_home, 'applications', DESKTOP_NAME),
        'icon': os.path.join(data_home, 'icons', 'hicolor', 'scalable', 'apps',
                             f'{APP_ID}.svg'),
        'launcher': os.path.join(data_home, 'rosbag_recorder_ui', 'launch-dashboard.sh'),
    }


def find_workspace_setup():
    """
    Find the setup.bash of the workspace this package was installed into.

    get_package_prefix gives <ws>/install/rosbag_recorder_ui, so the workspace
    setup is two levels up. Falls back to an empty string when the layout is
    unfamiliar, in which case the launcher just relies on the ROS setup.
    """
    try:
        prefix = get_package_prefix('rosbag_recorder_ui')
    except Exception:                                     # noqa: BLE001
        return ''
    candidate = os.path.join(os.path.dirname(prefix), 'setup.bash')
    if os.path.exists(candidate):
        return candidate
    candidate = os.path.join(os.path.dirname(os.path.dirname(prefix)),
                             'install', 'setup.bash')
    return candidate if os.path.exists(candidate) else ''


def install(keep_domain=True):
    target = paths()
    for path in target.values():
        os.makedirs(os.path.dirname(path), exist_ok=True)

    with open(target['icon'], 'w') as handle:
        handle.write(icons.app_icon_svg())

    distro = os.environ.get('ROS_DISTRO', 'humble')
    domain = os.environ.get('ROS_DOMAIN_ID', '')
    domain_line = (f'export ROS_DOMAIN_ID={domain}'
                   if keep_domain and domain else '')
    with open(target['launcher'], 'w') as handle:
        handle.write(LAUNCHER_TEMPLATE.format(
            ros_setup=f'/opt/ros/{distro}/setup.bash',
            workspace_setup=find_workspace_setup(),
            domain_line=domain_line))
    mode = os.stat(target['launcher']).st_mode
    os.chmod(target['launcher'], mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)

    with open(target['desktop'], 'w') as handle:
        handle.write(DESKTOP_TEMPLATE.format(launcher=target['launcher'],
                                             icon=target['icon']))
    _refresh_caches()

    print('Installed the ROS 2 Bag Recorder launcher:')
    for key in ('desktop', 'launcher', 'icon'):
        print(f'  {key:9} {target[key]}')
    if domain_line:
        print(f'\nPinned ROS_DOMAIN_ID={domain} into the launcher.')
    print('\nLaunching from the grid starts the bridge and the dashboard together,\n'
          'unless a bridge is already running on this ROS_DOMAIN_ID, in which case\n'
          'it connects to that one. Right-click the icon for "Dashboard only" if the\n'
          'bridge runs on a robot.')
    print('\nIt should appear in the application grid; log out and back in if not.')
    return 0


def uninstall():
    removed = []
    for key, path in paths().items():
        if os.path.exists(path):
            os.remove(path)
            removed.append(path)
    launcher_dir = os.path.dirname(paths()['launcher'])
    if os.path.isdir(launcher_dir) and not os.listdir(launcher_dir):
        shutil.rmtree(launcher_dir, ignore_errors=True)
    _refresh_caches()
    if removed:
        print('Removed:')
        for path in removed:
            print(f'  {path}')
    else:
        print('Nothing to remove; the launcher was not installed.')
    return 0


def _refresh_caches():
    for command in (['update-desktop-database', os.path.join(_data_home(),
                                                             'applications')],
                    ['gtk-update-icon-cache', '-f', '-t',
                     os.path.join(_data_home(), 'icons', 'hicolor')]):
        try:
            subprocess.run(command, check=False, stdout=subprocess.DEVNULL,
                           stderr=subprocess.DEVNULL, timeout=20)
        except (OSError, subprocess.SubprocessError):
            continue


def main(argv=None):
    parser = argparse.ArgumentParser(
        prog='install_desktop_entry',
        description='Add the ROS 2 Bag Recorder to the Ubuntu application grid.')
    parser.add_argument('--uninstall', action='store_true',
                        help='Remove the launcher instead of installing it.')
    parser.add_argument('--no-domain', action='store_true',
                        help='Do not bake the current ROS_DOMAIN_ID into the launcher.')
    args = parser.parse_args(argv if argv is not None else sys.argv[1:])
    return uninstall() if args.uninstall else install(keep_domain=not args.no_domain)


if __name__ == '__main__':
    sys.exit(main())
